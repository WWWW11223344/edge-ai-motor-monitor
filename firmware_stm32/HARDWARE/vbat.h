#ifndef __VBAT_H
#define __VBAT_H  /* 防止重复包含 */

#include "stm32f4xx.h"  /* 标准外设库声明 */

/* ==========================================================================
 * 第 4 步补充 · 母线电压采集（电池体检）
 * --------------------------------------------------------------------------
 * 为什么要读这个？
 *   电机是「电压驱动」的：占空比固定时，母线电压一掉，转速就跟着掉。
 *   不读母线电压，就永远分不清「转速变慢」到底是
 *       ① 电机/负载有问题     还是   ② 电池没电 / 供电回路有电阻。
 *   更现实的一点：**没有万用表的时候，这是判断电池还有没有电的唯一办法。**
 *
 * 硬件（不用额外买任何东西，D153C 驱动板自带）：
 *   D153C 把母线电压经 **10k + 1k 分压（1/11）** 后，从 H2 第 5 脚 ADC 引出。
 *   只要把这一根线接到 PA4（P11 第 5 脚）就能读：
 *
 *       电池正极 ──┬── 10k ──┬── 1k ── GND
 *                 (VM)       │
 *                         H2-5 ADC ──飞线──> PA4 (ADC1_IN4)
 *
 *   于是：  ADC 引脚上的电压 = VM / 11
 *          ADC 读数 raw       = VM / 11 / 3.3V × 4095
 *          VM                 = raw / 4095 × 3.3V × 11     （原始码换算成母线电压）
 *
 * 电流那一路别搞混：
 *      PA4 (ADC1_IN4, P11 第 5 脚) <- 母线电压（本文件）
 *      PA5 (ADC1_IN5, P11 第 3 脚) <- ACS712 电流输出（第 5 步）
 *      PA1 绝对不能当 ADC 用（被板载以太网 PHY 占了）
 *
 * 量程与分辨率：
 *      上限 = 3.3V × 11 = 36.3V（3S 锂电 12.6V 只用到 1/3 量程，很安全）
 *      分辨率 = 3.3V / 4095 × 11 ≈ 8.9mV —— 判断「12.6V 还是 9V」绰绰有余
 * ========================================================================== */

#define VBAT_DIV_RATIO      11.0f   /* D153C 板载分压比 1/11（10k + 1k） */
#define VBAT_VREF           3.30f   /* ADC 参考电压 = VDDA = 3.3V */
#define VBAT_ADC_FULL       4095.0f /* 12 位 ADC 满量程 */
#define VBAT_ADC_AVG        8U      /* 每次读 8 次取平均，压掉噪声 */
#define VBAT_VALID_MIN      4.0f    /* 低于此值判为无效（D153C 母线最低 4.5V） */
#define VBAT_VALID_MAX      16.0f   /* 高于此值判为无效（3S 锂电与 D153C 都到不了） */

void     Vbat_Init(void);           /* 配 PA4 为模拟输入 + 打开 ADC1 */
float    Vbat_GetVolt(void);        /* 取母线电压，单位 V（已乘 11） */
uint16_t Vbat_GetRaw(void);         /* 取原始 ADC 值（0~4095），要标定时用 */
uint8_t  Vbat_IsValid(void);        /* 1 = 最近电压可用；0 = 通路缺失/越界/ADC 失败 */
uint16_t ADC1_ReadChannel(uint8_t ch);  /* 通用 ADC1 单通道读（PA4/PA5 共用，current.c 也用） */
uint8_t  ADC1_LastReadOk(void);     /* 1 = 最近一次 ADC 转换在超时前完成 */

#endif
