#ifndef __ENCODER_H
#define __ENCODER_H  /* 防止重复包含 */

#include "stm32f4xx.h"  /* 标准外设库声明 */

/* ==========================================================================
 * 第 4 步 · 编码器测速（转速检测）
 * --------------------------------------------------------------------------
 * 硬件接线（编码器一共 4 根线，多出来的第 5 根屏蔽线不用接）：
 *      编码器 VCC   -> 开发板 3V3
 *      编码器 GND   -> 开发板 GND
 *      编码器 A 相  -> PB6   （扩展排针 P8 第 50 脚）
 *      编码器 B 相  -> PB7   （扩展排针 P8 第 49 脚）
 *
 * 为什么不用操作手册上写的 PA6 / PA7？
 *   对着开发板原理图第 4 页（U10 芯片旁边的网络标号）一个脚一个脚查过：
 *       PA6 = DCMI_PCLK    -> 只引到摄像头排针，没插摄像头，本来能用
 *       PA7 = RMII_CRS_DV  -> 直接连到板载 LAN8720A 以太网 PHY 上了，**不能用**
 *   也就是手册里写的 PA7 是错的（那个脚被网口芯片占着）。
 *
 *   改用 PB6 / PB7 的理由：
 *       两个脚都只引到摄像头排针（PB6 = DCMI_D5，PB7 = DCMI_VSYNC），
 *       板子上没有任何芯片在驱动它们，拉低拉高都随意；
 *       而且它们在扩展排针 P8 上正好是**相邻的两脚 49 / 50**，接线最省事；
 *       它们对应 TIM4 的 CH1 / CH2，直接丢给 TIM4 的编码器模式就能用。
 *   （顺带避开：PB5 虽然也空，但它挂着板载 W25Q128 Flash 的 MOSI，
 *     PB3/PB4 更是 Flash 的 SCK/MISO，能不碰就不碰。）
 *
 * 测速原理：
 *   编码器 A/B 输出两路"正交方波"（相位差 90 度）。STM32 定时器的
 *   "编码器模式"能让**硬件**自动对 A/B 的边沿做计数 + 判方向，完全不占 CPU：
 *       正转 -> 计数器加；反转 -> 计数器减；
 *       A、B 两个通道的边沿都计数 -> 一圈脉冲数再乘以 4（四倍频）。
 *   所以电机转一整圈的总计数 = 每转脉冲数 x 4 x 减速比
 *                            = 13 x 4 x 20 = 1040
 *   固定时间读一次计数器，差值就是这段时间走过的格数，换算成"转/分"即可。
 * ========================================================================== */

/* ---- 机械/电气参数：以后换电机只改这几行 ---- */
#define ENC_PPR             13U     /* 编码器每转脉冲数（MG310 霍尔编码器 13 线） */
#define ENC_MULT            4U      /* 四倍频：A、B 两相都双边沿计数 */
#define ENC_GEAR            20U     /* 减速箱速比 1:20 */
#define ENC_CPR             (ENC_PPR * ENC_MULT * ENC_GEAR)   /* 每转计数 = 1040 */

/* ---- 采样周期 ---- */
#define ENC_SAMPLE_MS       100U    /* 每 100ms 采一次（够快又不会太抖） */

/* 换算系数：60000 是 1 分钟的毫秒数
 *   rpm = 差值 x 60000 / (1040 x 100) = 差值 x 0.5769 */
#define ENC_RPM_PER_CNT     0.576923f

void    Encoder_Init(void);         /* 配置 PB6/PB7 + TIM4 编码器模式 */
void    Encoder_Tick1ms(void);      /* 由 TIM7 中断每 1ms 调用一次 */
float   Encoder_GetRpm(void);       /* 取最近一次算出的转速（转/分，恒为正） */
int16_t Encoder_GetDelta(void);     /* 取最近 100ms 内的计数差（带正负，能看方向） */
int16_t Encoder_GetCount(void);     /* 取 TIM4 计数器的绝对值（绝对位置，转满 65536 回绕）*/
uint32_t Encoder_GetMs(void);       /* 上电以来的毫秒数（顺便当运行时间用） */

#endif
