/**
  * @brief  This function handles Hard Fault exception.
  * @param  None
  * @retval None
  */
void HardFault_Handler(void)
{
  /* 跑飞了也别让电机继续转：先把 TIM9 两路比较值清零再停在这里。
   * 否则程序卡死、PWM 却停在上一个占空比，电机会一直转下去。 */
  TIM9->CCR1 = 0U;
  TIM9->CCR2 = 0U;

  while (1)
  {
  }
}

